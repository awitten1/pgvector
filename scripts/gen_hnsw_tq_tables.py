#!/usr/bin/env python3
"""
Generate src/hnswtq_tables.h: Gaussian Lloyd-Max codebooks for the experimental
4-bit TurboQuant navigation codes (and nested refinement codes) in HNSW.

  * 4-bit codebook: symmetric Lloyd-Max quantizer for N(0,1) with 8 positive
    centroids c_0..c_7 (sign bit + 3-bit index).
  * Nested refinement (k = 6, 8): each positive 4-bit cell [t_u, t_{u+1}) gets
    its own 2^k-level Lloyd-Max codebook for N(0,1) restricted to that cell.
  * D_b: per-coordinate MSE of each quantizer (used for the per-vector scale).

Usage: python3 scripts/gen_hnsw_tq_tables.py > src/hnswtq_tables.h
"""

import math
import sys

import numpy as np

SQRT2 = math.sqrt(2.0)
_erfc = np.frompyfunc(lambda x: math.erfc(x), 1, 1)


def upper_tail(z):
    """Q(z) = P(Z >= z) for Z ~ N(0,1); works for arrays and +inf."""
    z = np.asarray(z, dtype=np.float64)
    return 0.5 * np.asarray(_erfc(z / SQRT2), dtype=np.float64)


def pdf(z):
    z = np.asarray(z, dtype=np.float64)
    with np.errstate(over="ignore", invalid="ignore"):
        out = np.exp(-0.5 * z * z) / math.sqrt(2.0 * math.pi)
    return np.where(np.isinf(z), 0.0, out)


def cell_means(edges):
    """Conditional means of N(0,1) on consecutive [edges[i], edges[i+1])."""
    prob = upper_tail(edges[:-1]) - upper_tail(edges[1:])
    return (pdf(edges[:-1]) - pdf(edges[1:])) / prob


def cell_mse(edges, centroids):
    """Sum over cells of integral (z - c)^2 phi(z) dz."""
    a, b = edges[:-1], edges[1:]
    prob = upper_tail(a) - upper_tail(b)
    m1 = pdf(a) - pdf(b)                                    # int z phi
    bphi = np.where(np.isinf(b), 0.0, b * pdf(b))
    m2 = prob + a * pdf(a) - bphi                           # int z^2 phi
    return float(np.sum(m2 - 2.0 * centroids * m1 + centroids * centroids * prob))


def quantile_in(lo, hi, probs, sigma):
    """Quantiles of N(0, sigma^2) truncated to [lo, hi) (bisection)."""
    qlo = upper_tail(lo / sigma)
    qhi = upper_tail(hi / sigma) if math.isfinite(hi) else 0.0
    out = []
    top = hi if math.isfinite(hi) else lo + 12.0 * sigma + 12.0
    for p in probs:
        target = qlo - p * (qlo - qhi)
        a, b = lo, top
        for _ in range(200):
            mid = 0.5 * (a + b)
            if upper_tail(mid / sigma) > target:
                a = mid
            else:
                b = mid
        out.append(0.5 * (a + b))
    return np.array(out)


def lloyd_max(lo, hi, levels, max_iter=20000, tol=1e-13):
    """Lloyd-Max codebook for N(0,1) restricted to [lo, hi)."""
    # High-resolution init: quantiles of the p^(1/3) density (N(0, 3))
    probs = (np.arange(levels) + 0.5) / levels
    c = quantile_in(lo, hi, probs, math.sqrt(3.0))
    for it in range(max_iter):
        mids = 0.5 * (c[:-1] + c[1:])
        edges = np.concatenate(([lo], mids, [hi]))
        new = cell_means(edges)
        delta = float(np.max(np.abs(new - c)))
        c = new
        if delta < tol:
            break
    mids = 0.5 * (c[:-1] + c[1:])
    edges = np.concatenate(([lo], mids, [hi]))
    return c, edges, it + 1, delta


def fmt_floats(vals, per_line=6, indent="\t"):
    items = [f"{v:.9e}f" for v in vals]
    lines = []
    for i in range(0, len(items), per_line):
        lines.append(indent + ", ".join(items[i:i + per_line]))
    return ",\n".join(lines)


def main():
    out = []
    c4, e4, it4, d4delta = lloyd_max(0.0, math.inf, 8, max_iter=200000, tol=1e-15)
    D4 = 2.0 * cell_mse(e4, c4)
    print(f"4-bit: {it4} iters, last delta {d4delta:.2e}, D4={D4:.9f}", file=sys.stderr)

    refs = {}
    for k in (6, 8):
        cells = []
        mse = 0.0
        for u in range(8):
            lo, hi = e4[u], e4[u + 1]
            c, e, it, delta = lloyd_max(lo, hi, 1 << k, max_iter=20000, tol=1e-13)
            mse += cell_mse(e, c)
            cells.append(c)
            print(f"k={k} cell {u}: [{lo:.4f}, {hi:.4f}) {it} iters, last delta {delta:.2e}", file=sys.stderr)
        refs[k] = (cells, 2.0 * mse)
        print(f"k={k}: D={2.0 * mse:.9e}", file=sys.stderr)

    out.append("/*")
    out.append(" * Generated by scripts/gen_hnsw_tq_tables.py - do not edit by hand.")
    out.append(" *")
    out.append(" * Gaussian Lloyd-Max codebooks for experimental TurboQuant navigation codes.")
    out.append(" * Values are positive centroids; the sign is stored separately.")
    out.append(" */")
    out.append("#ifndef HNSWTQ_TABLES_H")
    out.append("#define HNSWTQ_TABLES_H")
    out.append("")
    out.append("/* Per-coordinate MSE D_b of the b-bit quantizer for N(0,1) */")
    out.append(f"#define HNSW_TQ_D4 {D4:.17g}")
    out.append(f"#define HNSW_TQ_D10 {refs[6][1]:.17g}")
    out.append(f"#define HNSW_TQ_D12 {refs[8][1]:.17g}")
    out.append("")
    out.append("/* 4-bit codebook: positive centroids c_0..c_7 */")
    out.append("static const float hnsw_tq4_centroids[8] = {")
    out.append(fmt_floats(c4, per_line=4))
    out.append("};")
    out.append("")
    out.append("/* 4-bit cell boundaries t_1..t_7 (t_0 = 0, t_8 = inf) */")
    out.append("static const float hnsw_tq4_thresholds[7] = {")
    out.append(fmt_floats(e4[1:8], per_line=4))
    out.append("};")
    for k in (6, 8):
        cells, _ = refs[k]
        out.append("")
        out.append(f"/* Nested refinement, k = {k}: positive centroids c_(u,v) within 4-bit cell u */")
        out.append(f"static const float hnsw_tq_ref{k}[8][{1 << k}] = {{")
        blocks = []
        for u in range(8):
            blocks.append("\t{\n" + fmt_floats(cells[u], per_line=6, indent="\t\t") + "\n\t}")
        out.append(",\n".join(blocks))
        out.append("};")
    out.append("")
    out.append("#endif")
    print("\n".join(out))


if __name__ == "__main__":
    main()
